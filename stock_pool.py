def get_stock_codes():
    """
    Return unique stock codes from all V5 groups.
    """

    codes = set()

    for stocks in STOCK_GROUPS.values():
        codes.update(stocks)

    for stocks in BROAD_GROUPS.values():
        codes.update(stocks)

    return sorted(codes)


def get_groups(code):
    """
    Return all groups associated with a stock.

    Example:
        2330 ->
        [
            "半導體",
            "AI",
        ]
    """

    groups = []

    for group, stocks in STOCK_GROUPS.items():
        if code in stocks:
            groups.append(group)

    for group, stocks in BROAD_GROUPS.items():
        if code in stocks and group not in groups:
            groups.append(group)

    return groups



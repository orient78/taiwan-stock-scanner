def get_stock_codes():
    """Return unique stock codes."""

    codes = set()

    for stocks in STOCK_GROUPS.values():
        codes.update(stocks)

    return sorted(codes)


def get_groups(code):
    """Return every V5 sector associated with a stock."""

    groups = []

    for group, stocks in STOCK_GROUPS.items():
        if code in stocks:
            groups.append(group)

    return groups


